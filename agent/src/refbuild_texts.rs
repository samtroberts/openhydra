//! Text supply for reference building: `refbuild generate` and `refbuild texts`.
//!
//! A reference text only protects anything if a cheater can't have scored it with the honest model
//! in advance. Copying passages verbatim from a public corpus fails that (a determined cheater can
//! pre-score the whole corpus once), so texts here are either:
//!
//! * **generated** — sampled at temperature from an LLM (ideally a *different* model from the one the
//!   reference is for) with randomized topic × language × form prompts; nobody can predict them; or
//! * **cropped** from local files (permissively licensed code / prose) at a random line and a random
//!   length — teacher-forced log-probs depend on the exact context, so pre-scoring every possible crop
//!   is infeasible.
//!
//! `texts` mixes the sources, drops duplicates and writes a provenance manifest (which file or
//! generation each text came from) next to the texts.
//!
//! Measured on Qwen3.5-9B Q4_K_M (L4, 2026-10-01; honest = llama.cpp CUDA fa-off / CPU / mistral.rs,
//! substitutes = Q4_0 / Q3_K_M, 99.5% of random 24-text rounds): texts generated by a different model
//! (Gemma 4 E4B) separate well — substitutes' low end 1.39x the honest high end — while crops of
//! source code barely separate (1.04x: code is predictable enough that an honest CPU backend drifts as
//! far as a cheaper quant). Prefer generated prose; use code crops sparingly, if at all.

use std::collections::HashSet;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::Mutex;

use clap::Args;
use openhydra_agent::adapter::HttpClient;
use openhydra_agent::http::ReqwestClient;
use rand::rngs::StdRng;
use rand::{Rng, SeedableRng};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};

#[derive(Args)]
pub struct GenerateArgs {
    /// OpenAI-compatible engine base URL (vLLM, SGLang, llama.cpp, …).
    #[arg(long)]
    engine: String,
    /// Served model name.
    #[arg(long)]
    model: String,
    /// How many texts to generate.
    #[arg(long)]
    count: usize,
    /// JSON Lines output: one {"text", "form", "language", "topic", "source"} per line.
    #[arg(long)]
    out: PathBuf,
    /// Seed for the prompt choices (the sampled text itself is not reproducible, by design).
    #[arg(long, default_value_t = 1)]
    seed: u64,
    #[arg(long, default_value_t = 320)]
    max_tokens: u32,
    #[arg(long, default_value_t = 1.0)]
    temperature: f64,
    /// Requests in flight at once (the engine batches them).
    #[arg(long, default_value_t = 8)]
    concurrency: usize,
}

#[derive(Args)]
pub struct TextsArgs {
    /// A source as `generated:<file.jsonl>:<count>` or `files:<dir>:<count>` (repeatable).
    #[arg(long = "source", required = true)]
    sources: Vec<String>,
    /// Shortest crop, in characters.
    #[arg(long, default_value_t = 300)]
    min_chars: usize,
    /// Longest crop / generated text kept, in characters.
    #[arg(long, default_value_t = 1200)]
    max_chars: usize,
    #[arg(long, default_value_t = 1)]
    seed: u64,
    /// JSON array of texts (the input to `refbuild tokenize`).
    #[arg(long)]
    out: PathBuf,
    /// Provenance: where every text came from.
    #[arg(long)]
    manifest: PathBuf,
}

// A deliberately broad spread, so texts resemble the variety of real traffic.
const TOPICS: &[&str] = &[
    "monsoon farming", "a city bus network", "home espresso", "tax filing for freelancers", "a lost cat",
    "orbital mechanics", "a school science fair", "sourdough baking", "cricket strategy", "a data-center outage",
    "learning the violin", "urban beekeeping", "a museum heist novel", "renting a first apartment", "tidal energy",
    "a wedding toast", "migrating a database", "chess openings", "mountain rescue", "a village festival",
    "electric scooters", "medieval trade routes", "sleep hygiene", "a startup pitch", "coral reefs",
    "a noisy neighbour", "compiler optimisations", "train delays", "knitting patterns", "volcano monitoring",
    "a job interview", "street food", "solar panels on rooftops", "a football transfer", "ancient mathematics",
    "password managers", "a thunderstorm at sea", "public libraries", "container shipping", "a birthday surprise",
    "wildfire prevention", "learning to code at fifty", "a courtroom drama", "desert navigation", "tea ceremonies",
    "an insurance claim", "quantum computing basics", "a school reunion", "bicycle repair", "river pollution",
];
const LANGUAGES: &[&str] = &[
    "English", "English", "English", "Spanish", "French", "German", "Portuguese", "Italian", "Hindi", "Chinese",
    "Japanese", "Korean", "Russian", "Arabic", "Turkish", "Indonesian", "Vietnamese", "Dutch", "Polish", "Swahili",
];
const FORMS: &[&str] = &[
    "a short news report", "a product review", "an email to a colleague", "a recipe", "a technical explanation",
    "a dialogue between two people", "a short poem", "a Python function with comments", "a SQL query with a short explanation",
    "a contract clause", "a diary entry", "a scientific abstract", "a travel-guide paragraph", "a customer-support reply",
    "the opening of a children's story", "a forum question", "a meeting summary with action items", "a JSON configuration with comments",
    "a shell script with comments", "a persuasive paragraph",
];
/// Forms that are code / data: always written in English prose around them.
const CODE_FORMS: &[&str] = &["a Python function with comments", "a SQL query with a short explanation", "a JSON configuration with comments", "a shell script with comments"];

/// A randomized prompt: (prompt, form, language, topic).
fn prompt(rng: &mut StdRng) -> (String, &'static str, &'static str, &'static str) {
    let topic = TOPICS[rng.gen_range(0..TOPICS.len())];
    let form = FORMS[rng.gen_range(0..FORMS.len())];
    let language = if CODE_FORMS.contains(&form) { "English" } else { LANGUAGES[rng.gen_range(0..LANGUAGES.len())] };
    // Random concrete details make texts unique even when topic/form/language repeat.
    let (n, m) = (rng.gen_range(2..=97), rng.gen_range(1900..=2090));
    let text = format!(
        "Write {form} in {language} about {topic}. Mention the number {n} and the year {m} naturally. \
         About 150 words. Reply with the text only — no title, no preamble, no notes."
    );
    (text, form, language, topic)
}

/// The generated text from a chat-completion reply, with any reasoning block removed.
fn completion_text(reply: &str) -> Option<String> {
    let v: Value = serde_json::from_str(reply).ok()?;
    let content = v.pointer("/choices/0/message/content")?.as_str()?;
    let text = match (content.find("<think>"), content.find("</think>")) {
        (_, Some(end)) => &content[end + "</think>".len()..],
        (Some(_), None) => return None, // reasoning never finished
        _ => content,
    };
    let text = text.trim();
    (!text.is_empty()).then(|| text.to_string())
}

pub fn generate(a: GenerateArgs) -> Result<(), String> {
    let root = a.engine.trim_end_matches('/').trim_end_matches("/v1").to_string();
    let mut rng = StdRng::seed_from_u64(a.seed);
    let prompts: Vec<_> = (0..a.count).map(|_| prompt(&mut rng)).collect();
    let next = AtomicUsize::new(0);
    let out = Mutex::new(Vec::<Value>::new());
    let failures = AtomicUsize::new(0);
    let first_error = Mutex::new(None::<String>);
    std::thread::scope(|s| {
        for _ in 0..a.concurrency.max(1) {
            s.spawn(|| {
                let http = match ReqwestClient::new() {
                    Ok(h) => h,
                    Err(_) => return,
                };
                loop {
                    let i = next.fetch_add(1, Ordering::Relaxed);
                    let Some((p, form, language, topic)) = prompts.get(i) else { break };
                    let body = json!({
                        "model": a.model,
                        "messages": [{"role": "user", "content": p}],
                        "max_tokens": a.max_tokens,
                        "temperature": a.temperature,
                        "chat_template_kwargs": {"enable_thinking": false},
                    });
                    let reply = http.post_json(&format!("{root}/v1/chat/completions"), &body.to_string());
                    let text = match &reply {
                        Ok(r) => completion_text(r),
                        Err(e) => {
                            first_error.lock().unwrap_or_else(|e| e.into_inner()).get_or_insert_with(|| e.to_string());
                            None
                        }
                    };
                    match text {
                        Some(text) => {
                            let mut o = out.lock().unwrap_or_else(|e| e.into_inner());
                            o.push(json!({"text": text, "form": form, "language": language, "topic": topic,
                                          "source": format!("generated:{}", a.model)}));
                            if o.len() % 50 == 0 {
                                eprintln!("refbuild: generated {}/{}", o.len(), a.count);
                            }
                        }
                        None => {
                            failures.fetch_add(1, Ordering::Relaxed);
                        }
                    }
                }
            });
        }
    });
    let out = out.into_inner().unwrap_or_else(|e| e.into_inner());
    let lines: Vec<String> = out.iter().map(|v| v.to_string()).collect();
    std::fs::write(&a.out, lines.join("\n") + "\n").map_err(|e| format!("{}: {e}", a.out.display()))?;
    eprintln!("refbuild: generated {} texts ({} failed) → {}", out.len(), failures.load(Ordering::Relaxed), a.out.display());
    if let Some(e) = first_error.into_inner().unwrap_or_else(|e| e.into_inner()) {
        eprintln!("refbuild: first request error: {e}");
    }
    if out.is_empty() {
        return Err("no texts generated".into());
    }
    Ok(())
}

/// One requested source.
#[derive(Debug, PartialEq)]
enum Source {
    Generated { path: PathBuf, count: usize },
    Files { dir: PathBuf, count: usize },
}

fn parse_source(s: &str) -> Result<Source, String> {
    let (kind, rest) = s.split_once(':').ok_or_else(|| format!("source {s}: expected kind:path:count"))?;
    let (path, count) = rest.rsplit_once(':').ok_or_else(|| format!("source {s}: expected kind:path:count"))?;
    let count: usize = count.parse().map_err(|_| format!("source {s}: bad count"))?;
    match kind {
        "generated" => Ok(Source::Generated { path: path.into(), count }),
        "files" => Ok(Source::Files { dir: path.into(), count }),
        other => Err(format!("source {s}: unknown kind {other} (generated or files)")),
    }
}

const TEXT_EXTENSIONS: &[&str] = &["py", "rs", "c", "cc", "cpp", "h", "hpp", "go", "js", "ts", "md", "txt", "sql", "sh", "toml", "yaml", "yml", "json"];

/// Every readable text file under `dir` with a known extension, 400 B – 2 MB, skipping hidden paths.
fn collect_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    for e in entries.flatten() {
        let p = e.path();
        if p.file_name().and_then(|n| n.to_str()).is_some_and(|n| n.starts_with('.')) {
            continue;
        }
        match e.file_type() {
            Ok(t) if t.is_dir() => collect_files(&p, out),
            Ok(t) if t.is_file() => {
                let ext_ok = p.extension().and_then(|x| x.to_str()).is_some_and(|x| TEXT_EXTENSIONS.contains(&x));
                let size_ok = e.metadata().is_ok_and(|m| (400..=2_000_000).contains(&m.len()));
                if ext_ok && size_ok {
                    out.push(p);
                }
            }
            _ => {}
        }
    }
}

/// A random crop of whole lines from `content`, between `min` and `max` characters, or `None`.
fn crop_lines(content: &str, min: usize, max: usize, rng: &mut StdRng) -> Option<String> {
    let lines: Vec<&str> = content.lines().collect();
    if lines.is_empty() {
        return None;
    }
    let target = rng.gen_range(min..=max.max(min));
    let start = rng.gen_range(0..lines.len());
    let mut out = String::new();
    for line in &lines[start..] {
        if out.len() + line.len() + 1 > max && out.len() >= min {
            break;
        }
        out.push_str(line);
        out.push('\n');
        if out.len() >= target {
            break;
        }
    }
    let out = out.trim_end().to_string();
    // Skip crops that are mostly blank or a single repeated character (license banners, separators).
    let distinct: HashSet<char> = out.chars().filter(|c| !c.is_whitespace()).collect();
    (out.len() >= min && out.len() <= max && distinct.len() >= 12).then_some(out)
}

/// Cut a generated text to at most `max` characters at a line or sentence boundary.
fn trim_generated(text: &str, max: usize) -> String {
    if text.len() <= max {
        return text.to_string();
    }
    let mut cut = max;
    while !text.is_char_boundary(cut) {
        cut -= 1;
    }
    let head = &text[..cut];
    let at = head.rfind(['\n', '.', '。', '!', '?']).map(|i| i + head[i..].chars().next().map_or(1, char::len_utf8)).unwrap_or(cut);
    head[..at].trim_end().to_string()
}

pub fn texts(a: TextsArgs) -> Result<(), String> {
    let sources = a.sources.iter().map(|s| parse_source(s)).collect::<Result<Vec<_>, _>>()?;
    let mut rng = StdRng::seed_from_u64(a.seed);
    let mut seen = HashSet::new();
    let (mut texts, mut provenance, mut summary) = (Vec::new(), Vec::new(), Vec::new());
    let mut add = |text: String, origin: Value, texts: &mut Vec<String>, provenance: &mut Vec<Value>| -> bool {
        let digest = hex::encode(Sha256::digest(text.as_bytes()));
        if !seen.insert(digest.clone()) {
            return false;
        }
        texts.push(text);
        provenance.push(json!({"sha256": digest, "origin": origin}));
        true
    };
    for src in &sources {
        match src {
            Source::Generated { path, count } => {
                let raw = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
                let mut rows: Vec<Value> = raw.lines().filter_map(|l| serde_json::from_str(l).ok()).collect();
                // Deterministic shuffle so `count` takes a random subset.
                for i in (1..rows.len()).rev() {
                    rows.swap(i, rng.gen_range(0..=i));
                }
                let mut got = 0;
                for row in rows {
                    if got == *count {
                        break;
                    }
                    let Some(text) = row.get("text").and_then(Value::as_str) else { continue };
                    let text = trim_generated(text, a.max_chars);
                    if text.len() < a.min_chars {
                        continue;
                    }
                    let origin = json!({"kind": "generated", "file": path.display().to_string(),
                        "source": row.get("source"), "form": row.get("form"), "language": row.get("language")});
                    got += add(text, origin, &mut texts, &mut provenance) as usize;
                }
                summary.push(json!({"source": format!("generated:{}", path.display()), "requested": count, "produced": got}));
            }
            Source::Files { dir, count } => {
                let mut files = Vec::new();
                collect_files(dir, &mut files);
                files.sort();
                if files.is_empty() {
                    return Err(format!("{}: no text files found", dir.display()));
                }
                let (mut got, mut tries) = (0, 0);
                while got < *count && tries < count * 20 {
                    tries += 1;
                    let f = &files[rng.gen_range(0..files.len())];
                    let Ok(content) = std::fs::read_to_string(f) else { continue };
                    let Some(crop) = crop_lines(&content, a.min_chars, a.max_chars, &mut rng) else { continue };
                    let origin = json!({"kind": "file", "path": f.display().to_string()});
                    got += add(crop, origin, &mut texts, &mut provenance) as usize;
                }
                summary.push(json!({"source": format!("files:{}", dir.display()), "files": files.len(), "requested": count, "produced": got}));
            }
        }
    }
    // Interleave sources so any slice of the output is a mix.
    let mut order: Vec<usize> = (0..texts.len()).collect();
    for i in (1..order.len()).rev() {
        order.swap(i, rng.gen_range(0..=i));
    }
    let texts_out: Vec<&String> = order.iter().map(|&i| &texts[i]).collect();
    let prov_out: Vec<&Value> = order.iter().map(|&i| &provenance[i]).collect();
    std::fs::write(&a.out, serde_json::to_vec(&texts_out).map_err(|e| e.to_string())?).map_err(|e| format!("{}: {e}", a.out.display()))?;
    std::fs::write(
        &a.manifest,
        serde_json::to_vec_pretty(&json!({"seed": a.seed, "min_chars": a.min_chars, "max_chars": a.max_chars,
            "sources": summary, "texts": prov_out}))
        .map_err(|e| e.to_string())?,
    )
    .map_err(|e| format!("{}: {e}", a.manifest.display()))?;
    for s in &summary {
        eprintln!("refbuild: {}", s);
    }
    eprintln!("refbuild: {} texts → {} (provenance in {})", texts_out.len(), a.out.display(), a.manifest.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn prompts_are_varied_and_reproducible() {
        let mut a = StdRng::seed_from_u64(7);
        let mut b = StdRng::seed_from_u64(7);
        let pa: Vec<_> = (0..50).map(|_| prompt(&mut a).0).collect();
        let pb: Vec<_> = (0..50).map(|_| prompt(&mut b).0).collect();
        assert_eq!(pa, pb);
        assert!(pa.iter().collect::<HashSet<_>>().len() >= 49);
        let mut c = StdRng::seed_from_u64(1);
        for _ in 0..200 {
            let (_, form, language, _) = prompt(&mut c);
            if CODE_FORMS.contains(&form) {
                assert_eq!(language, "English");
            }
        }
    }

    #[test]
    fn completion_text_drops_reasoning() {
        let r = |c: &str| json!({"choices": [{"message": {"content": c}}]}).to_string();
        assert_eq!(completion_text(&r("  Hello world. ")).as_deref(), Some("Hello world."));
        assert_eq!(completion_text(&r("<think>plan</think>\nThe text.")).as_deref(), Some("The text."));
        assert_eq!(completion_text(&r("<think>never ends")), None);
        assert_eq!(completion_text(&r("   ")), None);
        assert_eq!(completion_text("{}"), None);
    }

    #[test]
    fn sources_parse() {
        assert_eq!(parse_source("files:/a/b:30").unwrap(), Source::Files { dir: "/a/b".into(), count: 30 });
        assert_eq!(parse_source("generated:g.jsonl:5").unwrap(), Source::Generated { path: "g.jsonl".into(), count: 5 });
        assert!(parse_source("web:x:1").is_err());
        assert!(parse_source("files:/a").is_err());
    }

    #[test]
    fn crops_are_whole_lines_within_bounds() {
        let content: String = (0..400).map(|i| format!("line {i}: some code = compute({i}, \"abc\") + 42;\n")).collect();
        let mut rng = StdRng::seed_from_u64(3);
        let mut crops = HashSet::new();
        for _ in 0..50 {
            if let Some(c) = crop_lines(&content, 300, 800, &mut rng) {
                assert!((300..=800).contains(&c.len()), "{}", c.len());
                assert!(c.starts_with("line "));
                crops.insert(c);
            }
        }
        assert!(crops.len() > 30, "crops vary");
        assert_eq!(crop_lines(&"=\n".repeat(500), 300, 800, &mut rng), None, "separator noise is skipped");
    }

    #[test]
    fn generated_texts_are_trimmed_at_a_boundary() {
        assert_eq!(trim_generated("short", 100), "short");
        let t = "First sentence. Second sentence is longer. Third.";
        assert_eq!(trim_generated(t, 30), "First sentence.");
        let cjk = "这是第一句。这是第二句，比较长一些。第三句。";
        let out = trim_generated(cjk, 30);
        assert!(out.ends_with('。') && out.len() <= 30, "{out}");
    }

    #[test]
    fn texts_mix_sources_dedupe_and_record_provenance() {
        let dir = tempfile::tempdir().unwrap();
        let code = dir.path().join("src");
        std::fs::create_dir(&code).unwrap();
        let body: String = (0..300).map(|i| format!("def f{i}(x):\n    return x * {i} + len('abcdefghijklmnop')\n")).collect();
        std::fs::write(code.join("a.py"), &body).unwrap();
        std::fs::write(code.join(".hidden.py"), &body).unwrap();
        let gen = dir.path().join("gen.jsonl");
        let para = "Das ist ein Beispieltext über Bienen in der Stadt, mit vielen Details und Zahlen wie 42. ".repeat(6);
        std::fs::write(&gen, format!("{}\n{}\n", json!({"text": para, "form": "x", "language": "German"}), json!({"text": para})))
            .unwrap();
        let (out, manifest) = (dir.path().join("t.json"), dir.path().join("m.json"));
        texts(TextsArgs {
            sources: vec![format!("generated:{}:5", gen.display()), format!("files:{}:10", code.display())],
            min_chars: 200,
            max_chars: 700,
            seed: 9,
            out: out.clone(),
            manifest: manifest.clone(),
        })
        .unwrap();
        let t: Vec<String> = serde_json::from_slice(&std::fs::read(&out).unwrap()).unwrap();
        let m: Value = serde_json::from_slice(&std::fs::read(&manifest).unwrap()).unwrap();
        assert_eq!(t.len(), 11, "the duplicate generated text counts once");
        assert_eq!(m["texts"].as_array().unwrap().len(), 11);
        assert!(m["texts"].as_array().unwrap().iter().all(|p| !p["origin"].to_string().contains(".hidden")));
    }
}
